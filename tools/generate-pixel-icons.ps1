foreach ($name in $icons.Keys) {
  $icon = $icons[$name]
  $grid = $icon.Grid
  $pixels = New-Object System.Text.StringBuilder

  for ($y = 0; $y -lt 16; $y++) {
    for ($x = 0; $x -lt 16; $x++) {
      if ($grid[$y][$x] -eq '#') {
        [void]$pixels.Append("    <rect x=`"$x`" y=`"$y`" width=`"1`" height=`"1`"/>`n")
      }
    }
  }

  $svg = @"
<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 16 16" shape-rendering="crispEdges">
  <g fill="$($icon.Color)">
$($pixels.ToString().TrimEnd())
  </g>
</svg>
"@
  [System.IO.File]::WriteAllText((Join-Path $OutDir "$name.svg"), $svg + "`n")
  "$name.svg"
}
